log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*" >&2; }

load_instance_state() {
  [[ -f "${INSTANCE_STATE_FILE}" ]] || return 0
  local line key val
  while IFS= read -r line || [[ -n "${line}" ]]; do
    [[ "${line}" =~ ^[[:space:]]*# ]] && continue
    [[ "${line}" =~ ^([A-Za-z_][A-Za-z0-9_]*)=(.*)$ ]] || continue
    key="${BASH_REMATCH[1]}"
    val="${BASH_REMATCH[2]}"
    if [[ -z "${!key:-}" ]]; then
      export "${key}=${val}"
    fi
  done < "${INSTANCE_STATE_FILE}"
}

save_instance_state() {
  local iid="$1" name="$2" user="${3:-}"
  cat > "${INSTANCE_STATE_FILE}" <<EOF
# Generated by scripts/ec2_jlab.sh. Override with env vars or re-run use/bind-instance.
REGION=${REGION}
INSTANCE_ID=${iid}
INSTANCE_NAME=${name}
SSH_USER=${user}
S3_BUCKET=${S3_BUCKET}
S3_CACHE_PREFIX=${S3_CACHE_PREFIX}
IAM_INSTANCE_PROFILE=${IAM_INSTANCE_PROFILE}
IAM_ROLE_NAME=${IAM_ROLE_NAME}
KEY_PATH=${KEY_PATH}
KEY_BASENAME=${KEY_BASENAME}
EOF
  log "Saved instance binding to ${INSTANCE_STATE_FILE}"
}

